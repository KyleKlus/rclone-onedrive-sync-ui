"""
Builds the exact rclone command lines.

This module only *builds* commands (lists of strings). It never runs
anything, which makes it easy to read, change and test.
"""

from pathlib import Path

from . import config
from .models import SyncMode
from .settings import AppSettings


class FilterFile:
    """
    Writes the user's exclusion patterns into an rclone filter file.

    The file is rewritten before every run. Its content is deterministic
    (same patterns -> same bytes), which matters because ``rclone bisync``
    remembers a hash of the filter file and complains when it changes.
    The same file is passed as --filters-file to bisync and as --filter-from
    to sync (see ``build_sync_command``).
    """

    def __init__(self, path: Path) -> None:
        self.path = path

    def write(self, exclusions: tuple) -> Path:
        lines = ["# Generated by OneDrive Sync. Edit the exclusions in the UI instead."]
        lines.extend(f"- {pattern}" for pattern in exclusions)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return self.path


class RcloneCommandBuilder:
    """Turns the user's settings into rclone command lines."""

    def __init__(self, binary: str) -> None:
        self._binary = binary

    def build_sync_command(
        self,
        mode: SyncMode,
        settings: AppSettings,
        filter_path: Path,
        resync: bool = False,
        dry_run: bool = False,
    ) -> list:
        """
        Two-way:   rclone bisync <local> <remote> ...   (path1=local, path2=OneDrive)
        Download:  rclone sync   <remote> <local> ...   (OneDrive is the source)
        """
        if mode is SyncMode.BISYNC:
            command = [self._binary, "bisync", settings.local_path, settings.remote]
            command += self._flags(config.BISYNC_FLAGS, settings.max_size)
            # bisync has its own flag for the filter file (it also remembers the
            # file's hash, so it notices when the exclusions change).
            command += ["--filters-file", str(filter_path)]
            if resync:
                # Initial run: build the baseline. "path2" = OneDrive wins.
                command += ["--resync", "--resync-mode", "path2"]
        else:
            command = [self._binary, "sync", settings.remote, settings.local_path]
            command += self._flags(config.DOWNLOAD_FLAGS, settings.max_size)
            # Plain `rclone sync` does NOT know --filters-file (that is bisync only);
            # the same file format is read with the generic --filter-from.
            command += ["--filter-from", str(filter_path)]

        if dry_run:
            command.append("--dry-run")
        return command

    def build_access_file_upload(self, settings: AppSettings, local_file: Path) -> list:
        """
        Copy the RCLONE_TEST file to OneDrive unless it is already there.
        Needed once, because ``bisync --check-access`` wants it on both sides.
        """
        target = join_remote_path(settings.remote, config.ACCESS_CHECK_FILENAME)
        return [self._binary, "copyto", "--ignore-existing", "-v", str(local_file), target]

    @staticmethod
    def _flags(base_flags: list, max_size: str) -> list:
        """Copy the configured flags, replacing the max-size value with the user's."""
        flags = list(base_flags)
        if config.MAX_SIZE_FLAG in flags:
            flags[flags.index(config.MAX_SIZE_FLAG) + 1] = max_size
        else:
            flags += [config.MAX_SIZE_FLAG, max_size]
        return flags


def join_remote_path(remote: str, name: str) -> str:
    """'onedrive:' + 'x' -> 'onedrive:x'   |   'onedrive:Docs' + 'x' -> 'onedrive:Docs/x'"""
    if remote.endswith(":") or remote.endswith("/"):
        return remote + name
    return f"{remote}/{name}"
