"""
Everything that talks to the rclone program, in two clearly separated halves:

1. Building commands   ``FilterFiles``, ``RcloneCommandBuilder``
                       Pure functions of a pair's setup. They only produce lists
                       of strings and never run anything, so they are easy to
                       read and to test.
2. Running commands    ``RcloneRunner``
                       Starts the process, streams its output line by line and
                       can cancel it from another thread.

``PairJob`` is the only caller: it builds a command, then hands it to its own runner.
"""

import subprocess
import threading
from pathlib import Path
from typing import Callable, Optional

from .. import config
from ..errors import RcloneNotFoundError
from ..models import SyncMode
from ..setup import PairSetup

# After asking rclone to stop politely, wait this long before killing it.
_KILL_GRACE_SECONDS = 10


# ======================================================================
# 1. Building commands
# ======================================================================

class FilterFiles:
    """
    Writes each folder pair's exclusion patterns into an rclone filter file.

    Every pair has its own file (``<directory>/<pair id>.txt``), because pairs
    can sync at the same time and each one has its own exclusions.

    A file is rewritten before every run. Its content is deterministic
    (same patterns -> same bytes), which matters because ``rclone bisync``
    remembers a hash of the filter file and complains when it changes.
    The same file is passed as --filters-file to bisync and as --filter-from
    to sync (see ``build_sync_command``).
    """

    def __init__(self, directory: Path) -> None:
        self._directory = directory

    def write(self, pair_id: str, exclusions: tuple) -> Path:
        """Write the filter file of one pair and return its path."""
        lines = ["# Generated by Rclone Sync. Edit the exclusions in the UI instead."]
        lines.extend(f"- {pattern}" for pattern in exclusions)
        path = self._directory / f"{pair_id}.txt"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return path


class RcloneCommandBuilder:
    """Turns the setup of one folder pair into rclone command lines."""

    def __init__(self, binary: str) -> None:
        self._binary = binary

    def build_sync_command(
        self,
        mode: SyncMode,
        setup: PairSetup,
        filter_path: Path,
        resync: bool = False,
        dry_run: bool = False,
    ) -> list:
        """
        Two-way:   rclone bisync <local> <remote> ...   (path1=local, path2=the remote)
        Download:  rclone sync   <remote> <local> ...   (the remote is the source)
        """
        if mode is SyncMode.BISYNC:
            command = [self._binary, "bisync", setup.local_path, setup.remote]
            command += self._flags(config.BISYNC_FLAGS, setup.max_size)
            # bisync has its own flag for the filter file (it also remembers the
            # file's hash, so it notices when the exclusions change).
            command += ["--filters-file", str(filter_path)]
            if resync:
                # Initial run: build the baseline. "path2" = the remote wins.
                command += ["--resync", "--resync-mode", "path2"]
        else:
            command = [self._binary, "sync", setup.remote, setup.local_path]
            command += self._flags(config.DOWNLOAD_FLAGS, setup.max_size)
            # Plain `rclone sync` does NOT know --filters-file (that is bisync only);
            # the same file format is read with the generic --filter-from.
            command += ["--filter-from", str(filter_path)]

        if dry_run:
            command.append("--dry-run")
        return command

    def build_access_file_upload(self, setup: PairSetup, local_file: Path) -> list:
        """
        Copy the RCLONE_TEST file to the remote unless it is already there.
        Needed once, because ``bisync --check-access`` wants it on both sides.
        """
        target = join_remote_path(setup.remote, config.ACCESS_CHECK_FILENAME)
        return [self._binary, "copyto", "--ignore-existing", "-v", str(local_file), target]

    def build_probe_command(self, remote_name: str) -> list:
        """!
        @brief The command that tests whether a remote's login works.
        @param remote_name A remote name without the colon.
        @return `rclone lsd <name>:` with short timeouts and no retries: it lists the
                top-level folders only, so it is cheap on any size of drive.
        """
        return [
            self._binary, "lsd", f"{remote_name}:",
            "--contimeout", "15s", "--timeout", "30s",
            "--retries", "1", "--low-level-retries", "1",
        ]

    def build_list_remotes_command(self) -> list:
        """
        List every remote rclone has configured, with its type:
        ``rclone listremotes --long``  ->  one ``name:  type`` line per remote.
        """
        return [self._binary, "listremotes", "--long"]

    @staticmethod
    def _flags(base_flags: list, max_size: str) -> list:
        """Copy the configured flags, replacing the max-size value with the user's."""
        flags = list(base_flags)
        if config.MAX_SIZE_FLAG in flags:
            flags[flags.index(config.MAX_SIZE_FLAG) + 1] = max_size
        else:
            flags += [config.MAX_SIZE_FLAG, max_size]
        return flags


def join_remote_path(remote: str, name: str) -> str:
    """'cloud:' + 'x' -> 'cloud:x'   |   'cloud:Docs' + 'x' -> 'cloud:Docs/x'"""
    if remote.endswith(":") or remote.endswith("/"):
        return remote + name
    return f"{remote}/{name}"


# ======================================================================
# 2. Running commands
# ======================================================================

class RcloneRunner:
    """
    Runs one rclone command at a time and can cancel it from another thread.
    Every ``PairJob`` has its own runner, so pairs never cancel each other.

    stderr is merged into stdout because rclone writes its ``-v`` log to
    stderr, and we want one ordered stream of lines.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._process: Optional[subprocess.Popen] = None
        self._cancel_requested = False

    def reset(self) -> None:
        """Forget an earlier cancel request. Call before starting a new job."""
        with self._lock:
            self._cancel_requested = False

    def run(self, command: list, on_line: Callable[[str], None]) -> int:
        """
        Run ``command``, call ``on_line`` for every output line, and return
        the exit code. Blocks until rclone has finished.
        """
        try:
            process = subprocess.Popen(
                command,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                bufsize=1,  # line buffered
            )
        except FileNotFoundError as error:
            raise RcloneNotFoundError(
                f"Could not start '{command[0]}'. Is rclone installed and on your PATH?"
            ) from error

        with self._lock:
            self._process = process
            cancelled_early = self._cancel_requested
        if cancelled_early:
            # Stop was pressed in the instant before the process existed.
            process.terminate()

        try:
            for line in process.stdout:
                on_line(line.rstrip("\r\n"))
            return process.wait()
        finally:
            process.stdout.close()
            with self._lock:
                self._process = None

    def terminate(self) -> None:
        """
        Ask the running rclone to stop. If it has not exited after a grace
        period it is killed.
        """
        with self._lock:
            self._cancel_requested = True
            process = self._process
        if process is None or process.poll() is not None:
            return
        process.terminate()
        timer = threading.Timer(_KILL_GRACE_SECONDS, self._kill_if_alive, args=(process,))
        timer.daemon = True
        timer.start()

    @staticmethod
    def _kill_if_alive(process: subprocess.Popen) -> None:
        if process.poll() is None:
            process.kill()
